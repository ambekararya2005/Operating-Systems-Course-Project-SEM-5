#!/usr/bin/env bash
# OS concept: The critical-section problem — Peterson, mutex, spinlock, semaphore;
#             process synchronisation in Linux (futex) — experiment E4 — Unit 3
#
# E4: two camps (threads) each add N to one shared inventory counter, under every racelab
# mode, R times each (runs interleaved: run 1 of every mode, then run 2, ...). Then the mutex
# (and, for comparison, the semaphore and spinlock) modes run under strace -f -e trace=futex -c,
# contended (2 threads) and uncontended (1 thread), to count the futex system calls.
#
#   usage: run_e4.sh [-r RUNS] [-n ITERS]
#     -r  runs per mode (default 10)
#     -n  increments per thread (default 1000000)
#   env: BIN_DIR (default build), RESULTS (default experiments/results),
#        STRACE_OUT (default docs/strace_futex.txt)
#
# Outputs: $RESULTS/e4.csv (one row per mode and run) and $STRACE_OUT. The counts of the
# racy modes, every runtime and the futex counts are real measurements and vary between runs.
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
BIN="$ROOT/${BIN_DIR:-build}"
RESULTS=${RESULTS:-$ROOT/experiments/results}
STRACE_OUT=${STRACE_OUT:-$ROOT/docs/strace_futex.txt}
PROG=${0##*/}

runs=10
iters=1000000
while getopts ":r:n:h" opt; do
    case "$opt" in
        r) runs=$OPTARG ;;
        n) iters=$OPTARG ;;
        h) sed -n 's/^#   //p; s/^#     /  /p' "${BASH_SOURCE[0]}"; exit 0 ;;
        :) echo "$PROG: -$OPTARG needs a value" >&2; exit 2 ;;
        *) echo "$PROG: unknown option -$OPTARG" >&2; exit 2 ;;
    esac
done
shift $((OPTIND - 1))
(( $# == 0 )) || { echo "$PROG: unexpected argument '$1'" >&2; exit 2; }
[[ $runs =~ ^[1-9][0-9]*$ && $iters =~ ^[1-9][0-9]*$ ]] || { echo "$PROG: -r and -n must be positive integers" >&2; exit 2; }
[[ -x "$BIN/racelab" ]] || { echo "$PROG: $BIN/racelab not built; run 'make'" >&2; exit 1; }

MODES="none peterson-nofence peterson spinlock mutex semaphore"
mkdir -p "$RESULTS"
OUT="$RESULTS/e4.csv"
rm -f "$OUT"
echo "E4: $(nproc) CPUs, kernel $(uname -r), 2 threads x $iters increments, $runs runs per mode"
for r in $(seq "$runs"); do
    for m in $MODES; do
        "$BIN/racelab" --mode "$m" --iters "$iters" --csv "$OUT" --run "$r" > /dev/null
    done
done

awk -F, 'NR == 1 { for (i = 1; i <= NF; i++) c[$i] = i; next }
    { m = $c["mode"]; if (!(m in n)) order[++k] = m
      n[m]++; err[m] += $c["error"]; ms[m] += $c["runtime_ms"]; fails[m] += ($c["error"] != 0)
      if (!(m in mn) || $c["error"] < mn[m]) mn[m] = $c["error"]
      if (!(m in mx) || $c["error"] > mx[m]) mx[m] = $c["error"] }
    END {
        printf "\n%-18s %12s %18s %12s %13s\n", "mode", "mean error", "min-max error", "runs failed", "mean runtime"
        for (i = 1; i <= k; i++) { m = order[i]
            printf "%-18s %12.1f %18s %8d/%-3d %10.1f ms\n", m, err[m] / n[m], mn[m] "-" mx[m], fails[m], n[m], ms[m] / n[m] }
    }' "$OUT"
echo
echo "wrote $OUT ($(($(wc -l < "$OUT") - 1)) runs)"

# ---- futex system calls under strace ---------------------------------------------------------
if ! command -v strace > /dev/null; then
    echo "$PROG: strace not installed (sudo apt install strace); $STRACE_OUT not written" >&2
    exit 0
fi
TMP=$(mktemp -d "${TMPDIR:-/tmp}/reliefos-e4.XXXXXX")
trap 'rm -rf "$TMP"' EXIT
{
    echo "# E4: futex system calls made by racelab ($iters increments per thread), counted with"
    echo "#   strace -f -e trace=futex -c build/racelab --mode M [--threads 1] --iters $iters"
    echo "# Generated by experiments/run_e4.sh on kernel $(uname -r), $(nproc) CPUs, $(strace -V | head -1)."
    echo "# Each run takes and releases the lock $iters x threads times; compare that with the futex calls."
    echo "# 3-5 calls are unavoidable bookkeeping: the start barrier and pthread_join (the exiting thread's"
    echo "# CLONE_CHILD_CLEARTID futex wake). Under strace the timing changes, so contention does too."
    for spec in "mutex 2" "mutex 1" "semaphore 2" "semaphore 1" "spinlock 2"; do
        read -r m t <<< "$spec"
        echo
        echo "== mode=$m threads=$t ($([[ $t == 2 ]] && echo contended || echo "uncontended: one thread"))"
        echo "\$ strace -f -e trace=futex -c build/racelab --mode $m --threads $t --iters $iters"
        strace -f -e trace=futex -c -o "$TMP/strace.txt" "$BIN/racelab" --mode "$m" --threads "$t" --iters "$iters"
        cat "$TMP/strace.txt"
    done
} > "$STRACE_OUT"
awk '/^== / { mode = $2 " " $3 } $NF == "futex" { printf "  %-26s futex calls: %s\n", mode, $4 }' "$STRACE_OUT"
echo "wrote $STRACE_OUT"
